CREATE OR REPLACE FUNCTION public.set_print_orders_updated_at()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  NEW.updated_at = now();
  IF NEW.payment_method = 'cod' AND NEW.cod_collected = true AND OLD.cod_collected IS DISTINCT FROM true THEN
    NEW.cod_collected_at = now();
    NEW.payment_status = 'paid';
  ELSIF NEW.cod_collected = false THEN
    NEW.cod_collected_at = NULL;
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.set_print_orders_updated_at() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS set_print_orders_updated_at ON public.print_orders;
CREATE TRIGGER set_print_orders_updated_at BEFORE UPDATE ON public.print_orders
  FOR EACH ROW EXECUTE FUNCTION public.set_print_orders_updated_at();

