CREATE OR REPLACE FUNCTION public.sync_print_order_status_from_job()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
DECLARE next_order_status text;
BEGIN
  next_order_status := CASE NEW.status
    WHEN 'ready' THEN 'accepted'
    WHEN 'printing' THEN 'printing'
    WHEN 'completed' THEN 'completed'
    WHEN 'failed' THEN 'failed'
    WHEN 'expired' THEN 'cancelled'
    ELSE 'pending'
  END;
  UPDATE public.print_orders
    SET order_status = next_order_status
    WHERE print_job_id = NEW.id AND order_status IS DISTINCT FROM next_order_status;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS sync_print_order_status_from_job ON public.print_jobs;
CREATE TRIGGER sync_print_order_status_from_job AFTER UPDATE OF status ON public.print_jobs
  FOR EACH ROW WHEN (OLD.status IS DISTINCT FROM NEW.status)
  EXECUTE FUNCTION public.sync_print_order_status_from_job();
