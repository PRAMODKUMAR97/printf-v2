-- PrintF v2 order, COD, OTP, and private document-storage configuration.
-- Idempotent for the current PrintF v2 schema; existing order/payment rows are preserved.

CREATE TABLE IF NOT EXISTS public.print_orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  customer_name text NOT NULL CHECK (char_length(trim(customer_name)) BETWEEN 2 AND 100),
  customer_mobile text NOT NULL,
  print_job_id uuid REFERENCES public.print_jobs(id) ON DELETE SET NULL,
  amount numeric(10,2) NOT NULL CHECK (amount >= 0),
  payment_method text NOT NULL CHECK (payment_method IN ('razorpay','cod')),
  payment_status text NOT NULL DEFAULT 'pending' CHECK (payment_status IN ('pending','paid','failed','refunded')),
  order_status text NOT NULL DEFAULT 'pending' CHECK (order_status IN ('pending','accepted','printing','completed','cancelled','failed')),
  cod_collected boolean NOT NULL DEFAULT false,
  cod_collected_at timestamptz,
  razorpay_order_id text,
  razorpay_payment_id text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT print_orders_cod_collected_requires_cod CHECK (cod_collected = false OR payment_method = 'cod')
);

